@pytestmark_libclang
def test_stub_report_counts(tmp_path):
    work = tmp_path / "work"
    work.mkdir()
    (work / "a.c").write_text("int a(void) { return 1; }\nint b(void) { return 2; }\n")
    (work / "b.c").write_text("int c(void) { return 3; }\n")
    report = stub_directory(work, write_header=True)
    assert report.files_processed == 2
    assert report.files_modified == 2
    assert report.functions_stubbed == 3


@pytestmark_libclang
def test_stub_report_serialises():
    r = StubReport()
    r.files_processed = 5
    r.skip("static_in_header", "x")
    d = r.to_dict()
    assert d["files_processed"] == 5
    assert d["functions_skipped"]["static_in_header"] == ["x"]
