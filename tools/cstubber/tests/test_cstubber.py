pytestmark_libclang = pytest.mark.skipif(
    not LIBCLANG_AVAILABLE,
    reason="libclang Python bindings not available — run inside the C base image",
)


def _fixture_pairs():
    inputs = sorted((FIXTURES / "input").glob("*.c"))
    return [(p, FIXTURES / "expected" / p.name) for p in inputs]


@pytestmark_libclang
@pytest.mark.parametrize("input_path,expected_path", _fixture_pairs())
def test_fixture_byte_match(tmp_path, input_path: Path, expected_path: Path):
    """Each fixture's input, after stubbing, must byte-match its expected output."""
    work = tmp_path / "work"
    work.mkdir()
    target = work / input_path.name
    shutil.copy(input_path, target)
    report = stub_directory(work, write_header=True)
    assert (work / "commit0_stub.h").exists()
    assert target.read_text() == expected_path.read_text(), (
        f"\n--- expected ---\n{expected_path.read_text()}\n"
        f"--- got ---\n{target.read_text()}\n--- report ---\n{report.to_dict()}"
    )


@pytestmark_libclang
def test_idempotency(tmp_path):
    """Running cstubber twice on the same file yields identical output."""
    work = tmp_path / "work"
    work.mkdir()
    target = work / "simple.c"
    target.write_text("int add(int a, int b) {\n    return a + b;\n}\n")

    stub_directory(work, write_header=True)
    first = target.read_text()
    header_first = (work / "commit0_stub.h").read_text()

    stub_directory(work, write_header=True)
    second = target.read_text()
    header_second = (work / "commit0_stub.h").read_text()

    assert first == second, "second stub run mutated already-stubbed file"
    assert header_first == header_second
    # No duplicate include line.
    assert second.count(STUB_INCLUDE_LINE) == 1


@pytestmark_libclang
def test_skip_dir_files_untouched(tmp_path):
    work = tmp_path / "work"
    (work / "src").mkdir(parents=True)
    (work / "tests").mkdir(parents=True)
    src_text = "int foo(void) { return 1; }\n"
    test_text = "int test_foo(void) { return 1; }\n"
    (work / "src" / "foo.c").write_text(src_text)
    (work / "tests" / "test_foo.c").write_text(test_text)

    stub_directory(work, write_header=True)

    assert STUB_MARKER in (work / "src" / "foo.c").read_text()
    # tests/ should be untouched.
    assert (work / "tests" / "test_foo.c").read_text() == test_text


