def test_load_compile_commands_resolves_relative_includes(tmp_path):
    cc = tmp_path / "compile_commands.json"
    cc.write_text(
        json.dumps(
            [
                {
                    "directory": str(tmp_path / "build"),
                    "command": "gcc -DDEBUG=1 -I../include -Isrc -std=c11 -o foo.o foo.c",
                    "file": "foo.c",
                }
            ]
        )
    )
    db = load_compile_commands(cc)
    flags = list(db.values())[0]
    assert "-DDEBUG=1" in flags
    assert "-std=c11" in flags
    abs_include = str((tmp_path / "include").resolve())
    assert ("-I" + abs_include) in flags


def test_load_compile_commands_handles_arguments_array(tmp_path):
    cc = tmp_path / "compile_commands.json"
    cc.write_text(
        json.dumps(
            [
                {
                    "directory": str(tmp_path),
                    "arguments": ["gcc", "-I.", "-DX=1", "-c", "foo.c"],
                    "file": "foo.c",
                }
            ]
        )
    )
    db = load_compile_commands(cc)
    flags = list(db.values())[0]
    abs_cwd = str(tmp_path.resolve())
    assert ("-I" + abs_cwd) in flags
    assert "-DX=1" in flags


